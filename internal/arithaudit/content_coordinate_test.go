func TestGeneratedCanonicalOriginArithmetic(t *testing.T) {
	c, findings := coordinateFindings(t, canonicalOriginFixture)
	if len(findings) != 1 {
		t.Fatalf("findings %d", len(findings))
	}
	if err := c.checkGeneratedResidual(findings[0]); err != nil {
		t.Fatal(err)
	}
	for _, source := range []string{strings.ReplaceAll(canonicalOriginFixture, "RemainingCanonicalTarget", "UnboundedTarget"), strings.ReplaceAll(canonicalOriginFixture, "probe:=runtime.NewWriter()", "probe:=arbitraryWriter()"), strings.ReplaceAll(canonicalOriginFixture, "target+14", "target+2147483647"), strings.ReplaceAll(canonicalOriginFixture, "present{", "present{target=2147483647;"), strings.ReplaceAll(canonicalOriginFixture, "github.com/gomaja/go-csn1/runtime", "example.com/unchecked/runtime")} {
		c, findings := coordinateFindings(t, source)
		refused := false
		for _, f := range findings {
			if err := c.checkGeneratedResidual(f); err != nil {
				refused = true
			}
		}
		if !refused {
			t.Fatal("unbounded canonical target inherited proof")
		}
	}
}

const contentInputOffsetFixture = `package sample
import "github.com/gomaja/go-csn1/runtime"
func decodeContentBytes(data []byte, collector *runtime.Collector) (runtime.Decoded[Content], error) {
 if err := runtime.CheckInput(data); err != nil { return runtime.Decoded[Content]{}, err }
 if len(data) < 13 { return runtime.Decoded[Content]{}, &runtime.DecodeError{Kind:runtime.Truncated, Offset:runtime.InputBits(data)+14, Detail:"Content requires at least 101 bits"} }
 return runtime.Decoded[Content]{}, nil
}
`

func TestGeneratedContentInputOffsetArithmetic(t *testing.T) {
	for _, tc := range []struct{ name, old, replacement string }{
		{name: "generated bytes decoder"},
		{"exported decoder", "decodeContentBytes", "DecodeContent"},
		{"without collector", ", collector *runtime.Collector", ""},
		{"explicit runtime alias", `import "github.com/gomaja/go-csn1/runtime"`, `import runtime "github.com/gomaja/go-csn1/runtime"`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			text := strings.Replace(contentInputOffsetFixture, tc.old, tc.replacement, 1)
			if tc.old == "" {
				text = contentInputOffsetFixture
			}
			c, findings := coordinateFindings(t, text)
			checked := 0
			for _, f := range findings {
				if f.Expression == "runtime.InputBits(data) + 14" {
					checked++
					if err := c.checkGeneratedResidual(f); err != nil {
						t.Fatal(err)
					}
				}
			}
			if checked != 1 {
				t.Fatalf("offset expressions %d", checked)
			}
		})
	}
}

func TestGeneratedContentInputOffsetArithmeticRefusesMutations(t *testing.T) {
	for _, tc := range []struct{ name, old, replacement string }{
		{"missing input guard", `if err := runtime.CheckInput(data); err != nil { return runtime.Decoded[Content]{}, err }`, ``},
		{"nonrejecting input guard", `return runtime.Decoded[Content]{}, err`, `_ = err`},
		{"ignored input error", `err != nil`, `err == nil`},
		{"wrong guard input", `runtime.CheckInput(data)`, `runtime.CheckInput(other)`},
		{"wrong runtime path", `github.com/gomaja/go-csn1/runtime`, `example.test/unsafe/runtime`},
		{"wrong runtime alias", `import "github.com/gomaja/go-csn1/runtime"`, `import other "github.com/gomaja/go-csn1/runtime"`},
		{"shadow runtime binding", `func decodeContentBytes`, `var runtime OtherRuntime; func decodeContentBytes`},
		{"wrong data type", `data []byte`, `data []uint64`},
		{"shadow byte builtin", `func decodeContentBytes`, `type byte uint64; func decodeContentBytes`},
		{"import shadows len builtin", `import "github.com/gomaja/go-csn1/runtime"`, `import "github.com/gomaja/go-csn1/runtime"; import len "example.test/len"`},
		{"nonrejecting nil return", `return runtime.Decoded[Content]{}, err`, `return runtime.Decoded[Content]{}, nil`},
		{"shadow len builtin", `func decodeContentBytes`, `func len([]byte) int {return 0}; func decodeContentBytes`},
		{"wrong input", `runtime.InputBits(data)`, `runtime.InputBits(other)`},
		{"wrong constant", `+14`, `+2147483647`},
		{"wrong operation", `+14`, `*14`},
		{"wrong len input", `len(data) < 13`, `len(other) < 13`},
		{"nonliteral minimum", `len(data) < 13`, `len(data) < minimum`},
		{"zero minimum", `len(data) < 13`, `len(data) < 0`},
		{"wrong comparison", `len(data) < 13`, `len(data) > 13`},
		{"nontruncated error", `Kind:runtime.Truncated`, `Kind:runtime.Limit`},
		{"untyped error", `&runtime.DecodeError`, `&OtherError`},
		{"not returned", `return runtime.Decoded[Content]{}, &runtime.DecodeError`, `_ = &runtime.DecodeError`},
		{"wrong zero result", `return runtime.Decoded[Content]{}, &runtime.DecodeError`, `return runtime.Decoded[Other]{}, &runtime.DecodeError`},
		{"data reassigned", `if len(data) < 13`, `data=other; if len(data) < 13`},
		{"data escapes", `if len(data) < 13`, `escape(data); if len(data) < 13`},
		{"data mutated", `if len(data) < 13`, `data=append(data,0); if len(data) < 13`},
		{"branch input mutation", `if len(data) < 13 {`, `if len(data) < 13 {data=other;`},
		{"unrelated arithmetic", `Offset:runtime.InputBits(data)+14`, `Offset:0`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if !strings.Contains(contentInputOffsetFixture, tc.old) {
				t.Fatal("mutation did not apply")
			}
			source := strings.Replace(contentInputOffsetFixture, tc.old, tc.replacement, 1)
			if tc.name == "unrelated arithmetic" {
				source = strings.Replace(source, `return runtime.Decoded[Content]{}, nil`, `_ = runtime.InputBits(data)+14; return runtime.Decoded[Content]{}, nil`, 1)
			}
			c, findings := coordinateFindings(t, source)
			checked := 0
			for _, f := range findings {
				if strings.Contains(f.Expression, "InputBits(") {
					checked++
					if err := c.checkGeneratedResidual(f); err == nil {
						t.Fatalf("unsafe offset accepted: %s", f.Expression)
					}
				}
			}
			if checked != 1 {
				t.Fatalf("mutated offset expressions %d", checked)
			}
		})
	}
}

